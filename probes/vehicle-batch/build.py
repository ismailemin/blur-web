"""Batch-compile staged vehicle data for a list of roster-spec entries.

One spec (`probes/vehicle-batch/spec/cars.json`, generated by
`tools/spec_gen.py`) drives the whole chain. For every selected car this tool
produces, in `_work/vehicle-batch/<slug>/`:

  manifest.json        committed car-parts manifest  (proven build_manifest.py)
  mesh.json            LOD0 positions/indices/UV0   (same build)
  scene-report.json    committed Scene reader output (same build)
  materials/           independent material traversal (tools/inspect_car_materials.py)
  wheels/              decoded wheel model + Scene/Model reader output
  ghost-inputs.json    the two ghost files this car needs and how they are made
  integration.json     roster entry, ghost index fragment, guard pin values
  staged.json          resumable identity: input hashes + artifact hashes

It never edits `probes/e1-drive`, `probes/car-parts`, `probes/car-materials`,
`tools/`, the web application, the engine, `upstream/` or `game-data/`.

Usage:
  python probes/vehicle-batch/build.py [--scope remaining|all|roster]
         [--only <slug|index>[,<slug|index>...]] [--dry-run] [--no-resume]
         [--out-root <dir>] [--cache <dir>]
"""

