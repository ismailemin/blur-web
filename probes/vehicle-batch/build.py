def summarize(results: list[dict], spec: dict, spec_path: Path, out_root: Path,
              cache: Path, scope: str, tool_id: dict) -> dict:
    staged = [row for row in results if row["status"] in ("staged", "skipped")]
    blocked = [row for row in results if row["status"] == "blocked"]
    partial = [row for row in results if row["status"] == "partial"]
    records = [row["car"] for row in results if row["status"] in ("staged", "skipped")]

    def total(key_path: str) -> int:
        value = 0
        for record in records:
            node = record
            for part in key_path.split("."):
                node = node.get(part) if isinstance(node, dict) else None
                if node is None:
                    break
            value += int(node or 0)
        return value

    summary = {
        "kind": "blur.vehicle-batch.summary",
        "version": 1,
        "generatedBy": "probes/vehicle-batch/build.py",
        "scope": scope,
        "outRoot": rel(out_root),
        "cache": rel(cache),
        "spec": {
            "path": rel(spec_path),
            "sha256": sha256_file(spec_path),
            "counts": spec["counts"],
        },
        "tools": tool_id,
        "counts": {
            "selected": len(results),
            "staged": len(staged),
            "rebuilt": len([row for row in results if row["status"] == "staged"]),
            "resumed": len([row for row in results if row["status"] == "skipped"]),
            "partial": len(partial),
            "blocked": len(blocked),
            "errors": len([row for row in results if row["status"] == "error"]),
            "classA": sum(1 for row in results if row["car"].get("class") == "A"),
            "classB": sum(1 for row in results if row["car"].get("class") == "B"),
            "classC": sum(1 for row in results if row["car"].get("class") == "C"),
        },
        "aggregates": {
            "bodyDraws": total("body.drawCount") ,
            "parts": total("body.partCount"),
            "wheelDraws": total("body.wheelDrawCount"),
            "provenWheelDraws": total("body.provenWheelDrawCount"),
            "ambiguousWheelDraws": total("body.ambiguousWheelDrawCount"),
            "triangles": total("body.triangleCount"),
            "vertices": total("body.vertexCount"),
            "uv0ValidVertices": total("body.scene.uv0ValidVertices"),
            "uv0Bytes": total("body.scene.uv0Bytes"),
            "staticAlbedoDraws": total("body.materials.staticAlbedoDraws"),
            "uniqueTextures": total("body.materials.uniqueTextureCount"),
            "textureSourceBytes": total("body.materials.sourceBytes"),
            "textureRgbaBytesEstimate": total("body.materials.rgbaBytes"),
            "bodyModelLogicalBytes": total("identity.logicalBytes"),
            "meshBytes": total("body.scene.meshBytes"),
            "indexBytes": total("body.scene.indexBytes"),
            "stagedBytesOnDisk": sum(
                sum(row["artifacts"][name]["bytes"] for name in
                    ("manifest", "mesh", "sceneReport"))
                for row in records),
        },
        "roster": {
            "countBefore": spec["counts"]["inRoster"],
            "countAfter": spec["counts"]["inRoster"] + sum(
                1 for record in records if record.get("scope") == "remaining"),
            "entries": [roster_entry_from_record(row) for row in records],
        },
        "ghosts": {
            "required": 2 * len(records),
            "state": "pending-main-agent",
            "command": "node probes/e1-drive/tools/verify_e1_drive.mjs --write-ghosts",
        },
        "records": [
            {
                "slug": row["slug"],
                "recordIndex": row["car"].get("recordIndex"),
                "class": row["car"].get("class"),
                "status": row["status"],
                "reason": row.get("reason"),
                "artifacts": row["car"].get("artifacts"),
                "body": {
                    "drawCount": row["car"].get("body", {}).get("drawCount"),
                    "triangleCount": row["car"].get("body", {}).get("triangleCount"),
                    "uniqueTextureCount":
                        row["car"].get("body", {}).get("materials", {})
                        .get("uniqueTextureCount"),
                } if row["status"] != "blocked" else None,
            }
            for row in results
        ],
        "limits": [
            "Staged data only: no roster, P52 committed material, geometry pin, ghost, "
            "web, chunk or browser change is made.",
            "A staged record proves the body/wheel model, part manifest, LOD0 mesh, "
            "scene report, UV0 and independent material traversal parse and agree. It "
            "is not a drive or full-game claim.",
            "Texture RGBA bytes are the independent traversal's bounded estimate, not "
            "the committed P52 decode.",
            "Wheel corner identity remains preview-paired where the manifest says so; "
            "no corner is guessed.",
            "The manifest hash recorded here is the staging build (source.model points "
            "at the staging cache). The committed hash is produced by "
            "build_all_manifests.py; mesh and scene-report hashes are path-independent.",
        ],
    }
    return summary


def roster_entry_from_record(record: dict) -> dict:
    alias = (record.get("identity") or {}).get("alias")
    route = (record.get("identity") or {}).get("route")
    if route == "alias" and alias:
        why = (f"batch compiler (class C): record {record['recordIndex']}/"
               f"{record['recordId']} resolves through AmaxVehicle "
               f"{alias['amaxTag']} to {record['identity']['pakPath']}; record-level "
               f"identity, no name similarity used.")
    else:
        why = (f"batch compiler (class {record['class']}): exact "
               f"{record['identity']['pakPath']}, {record['drivetrain']}, "
               f"{int(round(record['massKg']))} kg, {record['gears']}-speed.")
    entry = {
        "slug": record["slug"],
        "name": record["recordName"],
        "recordId": record["recordId"],
        "recordIndex": record["recordIndex"],
        "layout": f"{record['drivetrain']}, {int(round(record['massKg']))} kg, "
                  f"{record['gears']}-speed",
        "why": why,
    }
    if route == "alias" and alias:
        entry["model"] = record["identity"]["pakPath"]
        entry["modelMapping"] = {
            "source": "_work/vehicle-pipeline/c-aliases.json",
            "recordIndex": record["recordIndex"],
            "recordId": record["recordId"],
            "amaxTag": alias["amaxTag"],
            "amaxRecordId": alias["amaxRecordId"],
            "amaxRefIndex": alias["amaxRefIndex"],
            "rpType": "RP_CarDynamics",
            "handleResolvesToExactRecordId": alias["handleResolvesToExactRecordId"],
            "nameSimilarityUsed": alias["nameSimilarityUsed"],
            "reason": "AmaxVehicle.dynamics FlaskHandle -> XT refs -> RP_CarDynamics "
                      "id; engine builds models/vehicles/%s.model from the vehicle tag",
        }
    return entry


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec", type=Path, default=SPEC_DEFAULT)
    parser.add_argument("--scope", choices=("remaining", "all", "roster"),
                        default="remaining")
    parser.add_argument("--only", default=None,
                        help="comma-separated slugs or record indices")
    parser.add_argument("--out-root", type=Path, default=OUT_DEFAULT)
    parser.add_argument("--cache", type=Path, default=CACHE_DEFAULT)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--no-resume", action="store_true")
    args = parser.parse_args()

    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    if spec.get("kind") != "blur.vehicle-batch.spec":
        raise SystemExit(f"{args.spec} is not a blur.vehicle-batch.spec")

    cars = list(spec["cars"])
    if args.scope == "remaining":
        cars = [car for car in cars if car["scope"] == "remaining"]
    elif args.scope == "roster":
        cars = [car for car in cars if car["scope"] == "roster"]
    if args.only:
        wanted = {value.strip() for value in args.only.split(",") if value.strip()}
        cars = [car for car in cars
                if car["slug"] in wanted or str(car["recordIndex"]) in wanted]
        if not cars:
            raise SystemExit(f"--only selected no cars: {args.only}")

    out_root = args.out_root if args.out_root.is_absolute() else ROOT / args.out_root
    cache = args.cache if args.cache.is_absolute() else ROOT / args.cache
    tool_id = tool_hashes()

    plan = []
    for car in cars:
        if car["body"] is None:
            plan.append({"slug": car["slug"], "recordIndex": car["recordIndex"],
                         "class": car["class"], "action": "blocked",
                         "reason": car["bodyReason"]})
        else:
            plan.append({"slug": car["slug"], "recordIndex": car["recordIndex"],
                         "class": car["class"], "action": "stage",
                         "pakPath": car["body"]["pakPath"]})

    if args.dry_run:
        payload = {
            "kind": "blur.vehicle-batch.dry-run",
            "version": 1,
            "scope": args.scope,
            "spec": rel(args.spec),
            "outRoot": rel(out_root),
            "counts": {
                "selected": len(plan),
                "stage": sum(1 for row in plan if row["action"] == "stage"),
                "blocked": sum(1 for row in plan if row["action"] == "blocked"),
            },
            "plan": plan,
            "wrote": False,
        }
        print(json.dumps(payload, indent=1, sort_keys=True))
        return 0

    out_root.mkdir(parents=True, exist_ok=True)
    cache.mkdir(parents=True, exist_ok=True)
    results = []
    for car in cars:
        print(f"[{car['recordIndex']:>3}] {car['slug']} ({car['class']})", flush=True)
        try:
            result = stage_car(car, out_root, cache, tool_id,
                               resume=not args.no_resume)
        except StageBlocked as error:
            payload = {
                "kind": KIND,
                "version": 1,
                "status": "blocked",
                "slug": car["slug"],
                "recordIndex": car["recordIndex"],
                "recordId": car["recordId"],
                "class": car["class"],
                "reasons": [reason(error.code, error.detail)],
            }
            (out_root / car["slug"]).mkdir(parents=True, exist_ok=True)
            clear_stage_markers(out_root / car["slug"])
            write_json(out_root / car["slug"] / "blocked.json", payload)
            result = {"slug": car["slug"], "status": "blocked",
                      "reason": payload["reasons"][0], "car": payload}
        except stage_batch3.Unsupported as error:
            payload = {
                "kind": KIND,
                "version": 1,
                "status": "blocked",
                "slug": car["slug"],
                "recordIndex": car["recordIndex"],
                "recordId": car["recordId"],
                "class": car["class"],
                "reasons": [reason("stage-unsupported", str(error))],
            }
            (out_root / car["slug"]).mkdir(parents=True, exist_ok=True)
            clear_stage_markers(out_root / car["slug"])
            write_json(out_root / car["slug"] / "blocked.json", payload)
            result = {"slug": car["slug"], "status": "blocked",
                      "reason": payload["reasons"][0], "car": payload}
        except Exception as error:  # noqa: BLE001 - recorded, never hidden
            result = {
                "slug": car["slug"],
                "status": "error",
                "reason": reason("stage-failed", str(error)),
                "car": {
                    "slug": car["slug"],
                    "recordIndex": car["recordIndex"],
                    "recordId": car["recordId"],
                    "recordName": car["recordName"],
                    "class": car["class"],
                    "drivetrain": car["drivetrain"],
                    "massKg": car["massKg"],
                    "gears": car["gears"],
                    "blockers": car["blockers"],
                },
            }
        print(f"      -> {result['status']}"
              + (f" ({result['reason']['code']})" if result.get("reason") else ""),
              flush=True)
        results.append(result)

    summary = summarize(results, spec, args.spec, out_root, cache, args.scope,
                        tool_id)
    summary_path = out_root / "summary.json"
    write_json(summary_path, summary)

    staged = [row for row in results if row["status"] in ("staged", "skipped")]
    write_json(out_root / "roster.fragment.json", {
        "kind": "blur.vehicle-batch.roster-fragment",
        "version": 1,
        "target": "probes/e1-drive/cars/roster.json",
        "note": "Append these entries after the existing cars; never reorder the five A "
                "anchors. The main agent owns roster.json.",
        "entries": summary["roster"]["entries"],
    })
    write_json(out_root / "ghost.fragment.json", {
        "kind": "blur.vehicle-batch.ghost-fragment",
        "version": 1,
        "target": "probes/e1-drive/ghosts/index.json",
        "note": "Ghost values come from `verify_e1_drive.mjs --write-ghosts`; the "
                "fragment carries the required keys with null values and a typed "
                "pending status.",
        "cars": {row["car"]["slug"]: ghost_fragment_from_record(row["car"])
                 for row in staged},
    })
    write_json(out_root / "guard-pins.json", {
        "kind": "blur.vehicle-batch.guard-pins",
        "version": 1,
        "rosterCarsBefore": spec["counts"]["inRoster"],
        "rosterCarsAfter": spec["counts"]["inRoster"] + sum(
            1 for row in staged if row["car"].get("scope") == "remaining"),
        "cars": {row["car"]["slug"]: {
            "manifestSha256Staging": row["car"]["artifacts"]["manifest"]["sha256"],
            "meshSha256": row["car"]["artifacts"]["mesh"]["sha256"],
            "sceneReportSha256": row["car"]["artifacts"]["sceneReport"]["sha256"],
            "draws": row["car"]["body"]["drawCount"],
            "triangles": row["car"]["body"]["triangleCount"],
            "uniqueTextureCount": row["car"]["body"]["materials"]["uniqueTextureCount"],
            "rgbaBytesEstimate": row["car"]["body"]["materials"]["rgbaBytes"],
            "uvValues": 2 * row["car"]["body"]["scene"]["vertexCount"],
        } for row in staged},
        "note": "Mesh and scene-report hashes are path-independent and match the "
                "committed build. The manifest hash must be re-read from the "
                "regenerated _work/car-parts/cars/index.json.",
    })

    print(json.dumps({
        "status": ("PASS" if not [row for row in results
                                  if row["status"] in ("error", "partial")] else "PARTIAL"),
        "outRoot": rel(out_root),
        "summary": rel(summary_path),
        "summarySha256": sha256_file(summary_path),
        "counts": summary["counts"],
        "aggregates": summary["aggregates"],
    }, indent=1, sort_keys=True))
    return 0 if not [row for row in results
                     if row["status"] in ("error", "partial")] else 1


