// Build the committed WebAssembly feature probes used by the capability page.
//
// The .wat sources in probes/compat/reference/wasm-probes/ are assembled with
// the binaryen `wasm-as` that ships in the repository's Emscripten toolchain.
// The output is written twice:
//   * probes/compat/web/wasm-probes.js  — committed, base64 fixtures imported by
//     the capability page (a few dozen bytes per feature, not game data);
//   * _work/compat/wasm-probes.json     — evidence record (bytes + SHA-256).
//
// Usage: node probes/compat/tools/build_wasm_probes.mjs [--wasm-as <path>]
//
// Each probe validates only if the browser implements that feature, so the
// recorded result is a measured capability, not a lookup table.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const WAT_DIR = path.join(ROOT, 'probes/compat/reference/wasm-probes');
const OUT_DIR = path.join(ROOT, '_work/compat');
const OUT_MODULE = path.join(ROOT, 'probes/compat/web/wasm-probes.js');

const args = process.argv.slice(2);
const wasmAsIndex = args.indexOf('--wasm-as');
const WASM_AS = wasmAsIndex >= 0
  ? args[wasmAsIndex + 1]
  : path.join(ROOT, '_work/toolchains/emsdk/upstream/bin/wasm-as.exe');

if (!existsSync(WASM_AS)) {
  throw new Error('wasm-as not found at ' + WASM_AS + '; pass --wasm-as <path>');
}
mkdirSync(OUT_DIR, { recursive: true });
mkdirSync(path.join(OUT_DIR, 'wasm-probes'), { recursive: true });

const watFiles = readdirSync(WAT_DIR).filter((name) => name.endsWith('.wat')).sort();
const probes = {};
const record = {
  schema: 'blur.compat.wasm-probes',
  version: 1,
  assembler: { executable: path.relative(ROOT, WASM_AS).split(path.sep).join('/'), flags: ['--all-features'] },
  source: 'probes/compat/reference/wasm-probes/*.wat',
  probes: {}
};

for (const watName of watFiles) {
  const name = watName.slice(0, -4);
  const watPath = path.join(WAT_DIR, watName);
  const wasmPath = path.join(OUT_DIR, 'wasm-probes', name + '.wasm');
  const result = spawnSync(WASM_AS, [watPath, '--all-features', '-o', wasmPath], { encoding: 'utf8' });
  if (result.status !== 0) {
    throw new Error('wasm-as ' + name + ' failed: ' + (result.stdout || '') + (result.stderr || ''));
  }
  const bytes = readFileSync(wasmPath);
  const base64 = bytes.toString('base64');
  const sha256 = 'sha256:' + createHash('sha256').update(bytes).digest('hex');
  probes[name] = base64;
  record.probes[name] = { wat: 'probes/compat/reference/wasm-probes/' + watName, bytes: bytes.length, sha256, base64 };
}

const module = [
  '// Generated by probes/compat/tools/build_wasm_probes.mjs — do not edit by hand.',
  '// Small WebAssembly fixtures assembled from probes/compat/reference/wasm-probes/*.wat',
  '// with binaryen wasm-as --all-features. Each fixture validates only in a browser',
  '// that implements the named feature; the capability page records the result.',
  '',
  'export const WASM_FEATURE_PROBES = Object.freeze({',
  ...Object.entries(probes).map(([name, base64]) => '  ' + JSON.stringify(name) + ': ' + JSON.stringify(base64) + ','),
  '});',
  ''
].join('\n');
writeFileSync(OUT_MODULE, module, 'utf8');
writeFileSync(path.join(OUT_DIR, 'wasm-probes.json'), JSON.stringify(record, null, 2) + '\n', 'utf8');

console.log('probes: ' + Object.keys(probes).length + ' -> ' + path.relative(ROOT, OUT_MODULE));
for (const [name, info] of Object.entries(record.probes)) {
  console.log('  ' + name.padEnd(22) + info.bytes.toString().padStart(3) + ' B  ' + info.sha256);
}
